-- 029_leads_locale_ip_index.sql — Фаза 4 (приём заявки по разделу 8).
--
-- 1) leads.locale — мова сторінки, з якої надіслано заявку (розділ 10 стандарту; профіль A —
--    завжди 'uk', але колонка потрібна для майбутнього другого языка). Існуючі рядки НЕ
--    заповнюємо (дані клієнта не змінюємо); новий код пише 'uk' за замовчуванням.
-- 2) Індекс (ip_address, created_at desc) — під підрахунок rate limit «3 заявки / 10 хв з IP»
--    і дедуп за IP у вікні (обидва читають leads за IP і часом).
--
-- Ідемпотентно. Додаткова колонка не ламає старий код (він її не читає), тому міграцію можна
-- застосувати ДО деплою коду Фази 4 — і бажано так і зробити: новий код при відсутності
-- колонки повторює запис без locale (перехідний захист), але це зайвий запит і попередження в лозі.

alter table public.leads add column if not exists locale text;

comment on column public.leads.locale is 'Мова сторінки заявки (uk); профіль A — завжди uk';

create index if not exists idx_leads_ip_created on public.leads (ip_address, created_at desc);
