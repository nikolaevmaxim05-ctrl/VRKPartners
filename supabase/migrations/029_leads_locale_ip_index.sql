-- 029_leads_locale_ip_index.sql — Фаза 4 (приём заявки по разделу 8).
--
-- 1) leads.locale — язык страницы, с которой отправлена заявка (раздел 10 стандарта; профиль A —
--    всегда 'uk', но колонка нужна для будущего второго языка). Существующие строки НЕ
--    заполняем (данные клиента не меняем); новый код пишет 'uk' по умолчанию.
-- 2) Индекс (ip_address, created_at desc) — под подсчёт rate limit «3 заявки / 10 мин с IP»
--    и дедуп по IP в окне (оба читают leads по IP и времени).
--
-- Идемпотентно. Дополнительная колонка не ломает старый код (он её не читает), поэтому миграцию можно
-- применить ДО деплоя кода Фазы 4 — и желательно так и сделать: новый код при отсутствии
-- колонки повторяет запись без locale (переходная защита), но это лишний запрос и предупреждение в логе.

alter table public.leads add column if not exists locale text;

comment on column public.leads.locale is 'Мова сторінки заявки (uk); профіль A — завжди uk';

create index if not exists idx_leads_ip_created on public.leads (ip_address, created_at desc);
