-- 028_leads_order_no_offset.sql
-- leads.order_no — сквозной числовой Order ID, который идёт в Google Ads как Order ID
-- офлайн-конверсий; по нему сшиваются конверсии и корректировки RETRACT/RESTATE (миграция 020).
--
-- После переезда на новый Supabase-проект нумерация стартовала почти с нуля. Если новый
-- проект начнёт выдавать order_no, которые СТАРЫЙ проект уже отправил в Google Ads, корректировки
-- сшиваются с чужими конверсиями → коллизии в фиде. Поэтому сдвигаем счётчик далеко вверх,
-- чтобы новые order_no гарантированно не пересеклись со старыми (лендинг никогда не имел миллиона
-- лидов). greatest(...) делает миграцию безопасной для повторного запуска — счётчик
-- никогда не уменьшается. Владелец при необходимости может поднять значение до «max старого + запас».
select setval(
  'public.leads_order_no_seq',
  greatest(1000000, (select last_value from public.leads_order_no_seq)),
  true
);
