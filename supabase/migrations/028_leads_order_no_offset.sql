-- 028_leads_order_no_offset.sql
-- leads.order_no — наскрізний числовий Order ID, який іде у Google Ads як Order ID
-- офлайн-конверсій; по ньому зшиваються конверсії та корекції RETRACT/RESTATE (міграція 020).
--
-- Після переїзду на новий Supabase-проєкт нумерація стартувала майже з нуля. Якщо новий
-- проєкт почне видавати order_no, які СТАРИЙ проєкт уже відправив у Google Ads, корекції
-- зшиються з чужими конверсіями → колізії у фіді. Тому зсуваємо лічильник далеко вгору,
-- щоб нові order_no гарантовано не перетнулися зі старими (лендинг ніколи не мав мільйона
-- лідів). greatest(...) робить міграцію безпечною для повторного запуску — лічильник
-- ніколи не зменшується. Власник за потреби може підняти значення до «max старого + запас».
select setval(
  'public.leads_order_no_seq',
  greatest(1000000, (select last_value from public.leads_order_no_seq)),
  true
);
