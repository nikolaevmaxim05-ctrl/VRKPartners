-- 022_normalize_lead_phones_e164.sql
-- C1: до цього телефони писались у БД маскою "+380 (XX) XXX-XX-XX", а дедуп шукав
-- за нормалізованим E.164 "+380XXXXXXXXX" — збіги ніколи не знаходились.
-- Тепер Zod-схема нормалізує телефон в E.164 при вставці. Тут — одноразова
-- нормалізація вже наявних записів, щоб дедуп працював і по старих лідах.
--
-- Обробляємо тільки українські номери (12 цифр, що починаються з 380).
-- Інші формати не чіпаємо. Ідемпотентно: рядки, що вже в E.164, не змінюються.

UPDATE leads
SET phone = '+' || regexp_replace(phone, '\D', '', 'g')
WHERE phone IS NOT NULL
  AND regexp_replace(phone, '\D', '', 'g') ~ '^380[0-9]{9}$'
  AND phone <> '+' || regexp_replace(phone, '\D', '', 'g');
