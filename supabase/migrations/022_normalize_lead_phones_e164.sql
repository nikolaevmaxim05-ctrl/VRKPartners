-- 022_normalize_lead_phones_e164.sql
-- C1: до этого телефоны писались в БД маской "+380 (XX) XXX-XX-XX", а дедуп искал
-- по нормализованному E.164 "+380XXXXXXXXX" — совпадения никогда не находились.
-- Теперь Zod-схема нормализует телефон в E.164 при вставке. Здесь — одноразовая
-- нормализация уже имеющихся записей, чтобы дедуп работал и по старым лидам.
--
-- Обрабатываем только украинские номера (12 цифр, начинающихся с 380).
-- Другие форматы не трогаем. Идемпотентно: строки, которые уже в E.164, не меняются.

UPDATE leads
SET phone = '+' || regexp_replace(phone, '\D', '', 'g')
WHERE phone IS NOT NULL
  AND regexp_replace(phone, '\D', '', 'g') ~ '^380[0-9]{9}$'
  AND phone <> '+' || regexp_replace(phone, '\D', '', 'g');
