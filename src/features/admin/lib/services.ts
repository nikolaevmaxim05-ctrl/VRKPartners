// Значения `leads.service` для UI админки (подпись и опции фильтра).
//
// Форма сайта пишет в service готовое украиноязычное название (не код), поэтому «перевод» тождественен,
// а неизвестные/старые значения показываем как есть. Поле «Послуга» из формы убрано в Фазе 3
// (никогда не рендерилось), так что список ниже — только для фильтрации ИСТОРИЧЕСКИХ лидов.

/**
 * Значение из БД → название для UI.
 * - null/undefined/'' → '—' (плейсхолдер для таблиц)
 * - любое другое значение — уже готовое украиноязычное название.
 */
export function getServiceLabel(value: string | null | undefined): string {
  if (!value) return '—'
  return value
}

/** Исторические значения service, которые могли записать старые версии формы. */
const LEGACY_SERVICES = ['Аудит', 'Стратегія', 'Прорахунок', 'Підготовка сайту'] as const

/** Список { value, label } для селектов/фильтров админки. */
export const SERVICE_OPTIONS: ReadonlyArray<{ value: string; label: string }> = LEGACY_SERVICES.map((s) => ({
  value: s,
  label: s,
}))
