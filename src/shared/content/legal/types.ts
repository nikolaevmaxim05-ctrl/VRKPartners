// Общие типы для юридических страниц (политика конфиденциальности, публичная оферта).

export type LegalSection = {
  /** Заголовок раздела (рендерится как h2). */
  heading: string
  /** Абзацы раздела — каждая строка становится отдельным <p>. */
  paragraphs: string[]
  /** Необязательный маркированный перечень под абзацами (каждая строка — <li>). */
  items?: string[]
}

export type LegalDocument = {
  /** Название документа — используется как h1 и в <title> вкладки. */
  title: string
  /** Дата последней редакции по умолчанию (напр. '17.07.2026').
   *  На странице показывается дата сохранения оверрайда из админки, а при его
   *  отсутствии — это значение из дефолтов. */
  updatedAt?: string
  /** Тело документа — массив разделов. */
  sections: LegalSection[]
}
