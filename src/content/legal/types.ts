// Спільні типи для легальних сторінок (політика конфіденційності, публічна оферта).

export type LegalSection = {
  /** Заголовок розділу (рендериться як h2). */
  heading: string
  /** Абзаци розділу — кожен рядок стає окремим <p>. */
  paragraphs: string[]
  /** Необовʼязковий маркований перелік під абзацами (кожен рядок — <li>). */
  items?: string[]
}

export type LegalDocument = {
  /** Назва документа — використовується як h1 і в <title> вкладки. */
  title: string
  /** Дата останньої редакції за замовчуванням (напр. '17.07.2026').
   *  На сторінці показується дата збереження оверрайду з адмінки, а за його
   *  відсутності — це значення з дефолтів. */
  updatedAt?: string
  /** Тіло документа — масив розділів. */
  sections: LegalSection[]
}
