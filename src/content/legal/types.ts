// Спільні типи для легальних сторінок (політика конфіденційності, публічна оферта).

export type LegalSection = {
  /** Заголовок розділу (рендериться як h2). */
  heading: string
  /** Абзаци розділу — кожен рядок стає окремим <p>. */
  paragraphs: string[]
}

export type LegalDocument = {
  /** Назва документа — використовується як h1 і в <title> вкладки. */
  title: string
  /** Дата останньої редакції (напр. '14.07.2026'). Показується лише коли документ опубліковано. */
  updatedAt?: string
  /**
   * Тіло документа. Поки масив ПОРОЖНІЙ — сторінка автоматично показує заглушку
   * «Документ готується до публікації» з контактами. Щойно sections заповнено —
   * рендериться повний текст, заглушка зникає сама (жодних правок компонентів).
   */
  sections: LegalSection[]
}
